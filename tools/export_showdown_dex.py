def to_id(text: str) -> str:
    return re.sub(r"[^a-z0-9]", "", text.lower())


def title_word(word: str) -> str:
    if not word:
        return word
    special = {"HP": "HP", "SP": "Sp"}
    up = word.upper()
    if up in special:
        return special[up]
    if word.isupper() and len(word) > 3:
        return word.title()
    return word[0].upper() + word[1:].lower() if word else word


def title_name(raw: str) -> str:
    parts = re.split(r"([ -])", raw.strip())
    return "".join(title_word(p) if p not in (" ", "-") else p for p in parts)


def es3_stringify(obj) -> str:
    buf = json.dumps(obj, ensure_ascii=True, separators=(",", ":"))
    reserved = {"return", "new", "delete"}

    def repl(match):
        key = match.group(1)
        if key in reserved:
            return match.group(0)
        return f"{key}:"

    return re.sub(r'"([A-Za-z][A-Za-z0-9]*)":', repl, buf)


def write_js(path: Path, export_name: str, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = f"// Auto-generated by tools/export_showdown_dex.py — do not edit\n\nexports.{export_name} = {es3_stringify(obj)};\n"
    path.write_text(body, encoding="utf-8")
    print(f"wrote {path} ({path.stat().st_size // 1024} KB)")


def parse_pbs_blocks(path: Path):
    """Yield (section_id, dict) from a generic PBS file."""
    current_id = None
    current = None
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = re.match(r"^\[([^\]]+)\]$", line)
        if m:
            if current_id is not None:
                yield current_id, current or {}
            current_id = m.group(1)
            current = {}
            continue
        if current is None:
            continue
        m = re.match(r"^(\w+)\s*=\s*(.*)$", line)
        if m:
            current[m.group(1)] = m.group(2).strip()
    if current_id is not None:
        yield current_id, current or {}


def parse_map_metadata():
    maps = {}
    map_id = None
    for raw in (PBS / "map_metadata.txt").read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("# See"):
            continue
        m = re.match(r"^\[(\d+)\]", line)
        if m:
            map_id = int(m.group(1))
            maps[map_id] = f"Map {map_id:03d}"
            continue
        if map_id is None:
            continue
        m = re.match(r"^Name\s*=\s*(.*)$", line)
        if m:
            name = m.group(1).strip()
            if name:
                maps[map_id] = name.replace("\\PN", "Player")
    return maps


def parse_evolutions(raw: str):
    if not raw:
        return []
    parts = [p.strip() for p in raw.split(",") if p.strip()]
    evos = []
    i = 0
    while i + 2 < len(parts):
        target = parts[i]
        method = parts[i + 1]
        param = parts[i + 2]
        evos.append({"species": target, "method": method, "param": param})
        i += 3
    return evos


def display_name(species_id: str, data: dict, form_name: str, is_form: bool) -> str:
    base_name = data.get("Name", title_name(species_id))
    if not is_form or not form_name:
        return base_name
    # Match Showdown hyphenated form names where possible
    if form_name.startswith("Mega ") and form_name.endswith(" X"):
        return f"{base_name}-Mega-X"
    if form_name.startswith("Mega ") and form_name.endswith(" Y"):
        return f"{base_name}-Mega-Y"
    if form_name.startswith("Mega "):
        return f"{base_name}-Mega"
    if form_name.endswith(" Forme") or form_name.endswith(" Form"):
        short = form_name.replace(" Forme", "").replace(" Form", "")
        if short in ("Alolan", "Galarian", "Hisuian", "Paldean"):
            return f"{base_name}-{short[:-2] if short.endswith('n') else short}"
        return f"{base_name}-{short}"
    if form_name in ("Alolan", "Galarian", "Hisuian", "Paldean"):
        return f"{base_name}-{form_name[:-2] if form_name.endswith('n') else form_name}"
    return f"{base_name}-{form_name}"


def forme_label(form_name: str) -> str:
    if not form_name:
        return ""
    if form_name.startswith("Mega ") and form_name.endswith(" X"):
        return "Mega-X"
    if form_name.startswith("Mega ") and form_name.endswith(" Y"):
        return "Mega-Y"
    if form_name.startswith("Mega "):
        return "Mega"
    if form_name.endswith(" Forme"):
        return form_name[:-6]
    if form_name.endswith(" Form"):
        return form_name[:-5]
    return form_name


def build_pokedex():
    base_paths = [
        PBS / "pokemon.txt",
        PBS / "pokemon_base_Gen_9_Pack.txt",
    ]
    form_paths = [
        PBS / "pokemon_forms.txt",
        PBS / "pokemon_forms_Gen_9_Pack.txt",
    ]

    bases_raw = parse_pbs_species_files(base_paths)
    base_map = {}
    for sid, data in bases_raw:
        base_map[sid] = data
    bases = list(base_map.items())
    base_map = {}
    for sid, data in bases:
        base_map[sid] = data
    bases = list(base_map.items())
    forms = parse_pbs_forms(form_paths)
    forms_by_species = defaultdict(list)
    for sid, fnum, fdata in forms:
        forms_by_species[sid].append((fnum, fdata))
    for sid in forms_by_species:
        forms_by_species[sid].sort(key=lambda x: x[0])

    pokedex = {}
    id_by_species = {}  # (SPECIES_ID, form_num) -> showdown id

    for dex_num, (sid, base) in enumerate(bases, start=1):
        entries = [(0, {}, base.get("FormName", ""))]
        for fnum, fdata in forms_by_species.get(sid, []):
            entries.append((fnum, fdata, fdata.get("FormName", f"Form {fnum}")))

        base_showdown_id = showdown_id(sid, entries[0][2] if entries[0][0] == 0 else "")
        base_display = display_name(
            sid, base, entries[0][2] if entries[0][0] == 0 else "",
            bool(entries[0][2]),
        )
        other_formes = []

        for fnum, fdata, form_name in entries:
            data = merge_form(base, fdata) if fnum else base
            is_form = bool(fnum or base.get("FormName"))
            name = display_name(sid, data, form_name or base.get("FormName", ""), is_form)
            entry_id = showdown_id(sid, form_name if fnum else base.get("FormName", ""))
            id_by_species[(sid, fnum)] = entry_id

            hp, atk, defense, spa, spd, spe, _bst = stats_from(data)
            t1, t2 = types_from(data)
            types = [t1] + ([t2] if t2 else [])

            abilities = {}
            ab_raw = data.get("Abilities", "")
            if ab_raw:
                ab_parts = [a.strip() for a in ab_raw.split(",") if a.strip()]
                if ab_parts:
                    abilities["0"] = title_name(ab_parts[0])
                if len(ab_parts) > 1:
                    abilities["1"] = title_name(ab_parts[1])
            ha = data.get("HiddenAbilities", "")
            if ha:
                abilities["H"] = title_name(ha.split(",")[0].strip())

            gender = GENDER_MAP.get(data.get("GenderRatio", "FemaleOneEighth"), {"M": 0.5, "F": 0.5})

            egg_groups = []
            for g in data.get("EggGroups", "").split(","):
                g = g.strip().upper()
                if g and g in EGG_GROUP_MAP:
                    egg_groups.append(EGG_GROUP_MAP[g])

            entry = {
                "num": dex_num,
                "name": name,
                "types": types,
                "genderRatio": gender,
                "baseStats": {
                    "hp": hp,
                    "atk": atk,
                    "def": defense,
                    "spa": spa,
                    "spd": spd,
                    "spe": spe,
                },
                "abilities": abilities,
                "heightm": float(data.get("Height", "1") or 1),
                "weightkg": float(data.get("Weight", "1") or 1),
                "color": title_name(data.get("Color", "Green")),
                "eggGroups": egg_groups,
                "gen": int(data.get("Generation", "9") or 9),
                "tier": "OU",
            }

            if data.get("Pokedex"):
                entry["desc"] = data["Pokedex"]

            if is_form:
                entry["baseSpecies"] = base_display
                entry["forme"] = forme_label(form_name or base.get("FormName", ""))
            else:
                entry["baseSpecies"] = name

            entry["spriteid"] = entry_id

            evos_raw = data.get("Evolutions", "")
            evo_list = parse_evolutions(evos_raw)
            if evo_list:
                evo_names = []
                for evo in evo_list:
                    target_data = base_map.get(evo["species"], {})
                    evo_names.append(display_name(evo["species"], target_data, "", False))
                entry["evos"] = evo_names
                if evo_list[0]["method"].lower() == "level":
                    try:
                        entry["evoLevel"] = int(evo_list[0]["param"])
                    except ValueError:
                        pass

            # prevo from reverse scan later
            pokedex[entry_id] = entry
            if is_form and name != base_display:
                other_formes.append(name)

        if other_formes and base_showdown_id in pokedex:
            pokedex[base_showdown_id]["otherFormes"] = other_formes
            pokedex[base_showdown_id]["formeOrder"] = [base_display] + other_formes

    # prevos
    for entry_id, entry in pokedex.items():
        for evo_name in entry.get("evos", []):
            evo_id = to_id(evo_name)
            if evo_id in pokedex:
                pokedex[evo_id]["prevo"] = entry["name"]
                if entry.get("evoLevel"):
                    pokedex[evo_id]["evoLevel"] = entry["evoLevel"]

    return pokedex, id_by_species


def build_moves():
    moves = {}
    for move_id, data in parse_pbs_blocks(PBS / "moves.txt"):
        name = data.get("Name", title_name(move_id))
        mid = to_id(name)
        category = data.get("Category", "Physical").capitalize()
        flags = {}
        for flag in data.get("Flags", "").split(","):
            flag = flag.strip()
            if not flag:
                continue
            key = flag[0].lower() + flag[1:]
            if key == "CanProtect":
                key = "protect"
            elif key == "CanMirrorMove":
                key = "mirror"
            elif key == "HighCriticalHitRate":
                key = "crit"
            elif key == "Sound":
                key = "sound"
            elif key == "Bomb":
                key = "bullet"
            else:
                key = to_id(key)
            flags[key] = 1

        entry = {
            "num": len(moves) + 1,
            "name": name,
            "type": title_type(data.get("Type", "NORMAL")),
            "category": category,
            "basePower": int(data.get("Power", "0") or 0),
            "accuracy": 100 if data.get("Accuracy", "100") == "0" else int(data.get("Accuracy", "100") or 100),
            "pp": int(data.get("TotalPP", "20") or 20),
            "priority": int(data.get("Priority", "0") or 0),
            "flags": flags,
            "desc": data.get("Description", ""),
            "shortDesc": data.get("Description", "")[:80],
            "gen": 9,
        }
        if entry["accuracy"] == 0:
            entry["accuracy"] = True
        moves[mid] = entry
    return moves


