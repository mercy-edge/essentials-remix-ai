def build_learnsets(pokedex):
    base_paths = [
        PBS / "pokemon.txt",
        PBS / "pokemon_base_Gen_9_Pack.txt",
    ]
    form_paths = [
        PBS / "pokemon_forms.txt",
        PBS / "pokemon_forms_Gen_9_Pack.txt",
    ]
    bases_raw = parse_pbs_species_files(base_paths)
    base_map = {}
    for sid, data in bases_raw:
        base_map[sid] = data
    bases = list(base_map.items())
    forms = parse_pbs_forms(form_paths)
    forms_by_species = defaultdict(list)
    for sid, fnum, fdata in forms:
        forms_by_species[sid].append((fnum, fdata))

    learnsets = {}

    def add_moves(entry_id, moves_key, prefix):
        raw = data.get(moves_key, "")
        if not raw:
            return
        parts = [p.strip() for p in raw.split(",") if p.strip()]
        i = 0
        while i + 1 < len(parts):
            try:
                level = int(parts[i])
            except ValueError:
                i += 1
                continue
            move_name = title_name(parts[i + 1])
            move_id = to_id(move_name)
            learnsets[entry_id]["learnset"].setdefault(move_id, []).append(f"{prefix}{level}")
            i += 2

    def add_list(entry_id, key, tag):
        raw = data.get(key, "")
        if not raw:
            return
        for move_token in raw.split(","):
            move_token = move_token.strip()
            if not move_token:
                continue
            move_id = to_id(title_name(move_token))
            learnsets[entry_id]["learnset"].setdefault(move_id, []).append(tag)

    for sid, base in bases:
        entries = [(0, {}, "")]
        for fnum, fdata in forms_by_species.get(sid, []):
            entries.append((fnum, fdata, fdata.get("FormName", "")))

        for fnum, fdata, form_name in entries:
            data = merge_form(base, fdata) if fnum else base
            entry_id = showdown_id(sid, form_name if fnum else base.get("FormName", ""))
            if entry_id not in pokedex:
                continue
            learnsets[entry_id] = {"learnset": {}}
            add_moves(entry_id, "Moves", "9L")
            add_list(entry_id, "TutorMoves", "9T")
            add_list(entry_id, "EggMoves", "9E")

    return learnsets


def parse_encounters():
    path = PBS / "encounters.txt"
    maps = defaultdict(lambda: {"slots": []})
    map_id = None
    enc_type = None

    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.rstrip()
        if not line.strip() or line.startswith("#---") or line.startswith("# See"):
            continue
        m = re.match(r"^\[(\d+)(?:,(\d+))?\]\s*(?:#\s*(.*))?$", line.strip())
        if m:
            map_id = int(m.group(1))
            enc_type = None
            continue
        if map_id is None:
            continue
        stripped = line.strip()
        sm = re.match(r"^(\d+),([A-Z0-9_]+),(\d+)(?:,(\d+))?$", stripped)
        if sm and enc_type:
            maps[map_id]["slots"].append({
                "type": enc_type,
                "chance": int(sm.group(1)),
                "species": sm.group(2),
                "min": int(sm.group(3)),
                "max": int(sm.group(4) or sm.group(3)),
            })
            continue
        tm = re.match(r"^([A-Za-z]+)(?:,(\d+))?$", stripped)
        if tm:
            enc_type = tm.group(1)
    return maps


def method_label(enc_type: str) -> str:
    if enc_type in LAND_ENC_TYPES:
        if enc_type == "Cave":
            return "Cave"
        if enc_type == "RockSmash":
            return "Rock Smash"
        return "Land"
    if enc_type in FISH_ENC_TYPES:
        return enc_type.replace("Rod", " Rod")
    if enc_type in WATER_ENC_TYPES:
        return enc_type
    return enc_type


def rarity_label(chance: int) -> str:
    if chance > 20:
        return "Common"
    if chance >= 5:
        return "Uncommon"
    return "Rare"


def build_encounters(pokedex):
    map_names = parse_map_metadata()
    enc_maps = parse_encounters()
    by_species = defaultdict(list)

    for map_id, block in sorted(enc_maps.items()):
        map_name = map_names.get(map_id, f"Map {map_id:03d}")
        for slot in block["slots"]:
            sid = slot["species"]
            entry_id = showdown_id(sid, "")
            if entry_id not in pokedex and to_id(sid) in pokedex:
                entry_id = to_id(sid)
            levels = str(slot["min"]) if slot["min"] == slot["max"] else f"{slot['min']}-{slot['max']}"
            by_species[entry_id].append({
                "map": map_name,
                "mapId": map_id,
                "method": method_label(slot["type"]),
                "rarity": rarity_label(slot["chance"]),
                "chance": slot["chance"],
                "levels": levels,
            })

    for entry_id in by_species:
        by_species[entry_id].sort(key=lambda x: (x["map"], x["method"], -x["chance"]))
    return dict(by_species)


def build_search_index(pokedex, moves, abilities):
    index = []
    for pid in sorted(pokedex.keys()):
        index.append(f"{pid} pokemon")
    for mid in sorted(moves.keys()):
        index.append(f"{mid} move")
    for aid in sorted(abilities.keys()):
        index.append(f"{aid} ability")
    for t in (
        "normal", "fire", "water", "electric", "grass", "ice", "fighting", "poison",
        "ground", "flying", "psychic", "bug", "rock", "ghost", "dragon", "dark", "steel", "fairy",
    ):
        index.append(f"{t} type")
    index.sort()

    battle_index = []
    for row in index:
        parts = row.split(" ")
        battle_index.append(parts)

    count_index = {}
    for t in (
        "Normal", "Fire", "Water", "Electric", "Grass", "Ice", "Fighting", "Poison",
        "Ground", "Flying", "Psychic", "Bug", "Rock", "Ghost", "Dragon", "Dark", "Steel", "Fairy",
    ):
        tid = to_id(t)
        count_index[f"{tid} move"] = sum(1 for m in moves.values() if m["type"] == t)
        count_index[f"{tid} pokemon"] = sum(
            1 for p in pokedex.values() if t in p.get("types", [])
        )

    return {
        "BattleSearchIndex": battle_index,
        "BattleSearchIndexOffset": [""] * len(battle_index),
        "BattleSearchCountIndex": count_index,
        "BattleArticleTitles": {},
    }


